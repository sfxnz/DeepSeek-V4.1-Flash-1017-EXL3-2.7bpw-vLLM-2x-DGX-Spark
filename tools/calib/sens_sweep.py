#!/usr/bin/env python3
"""Plan the smooth-mode sensitivity sweep into GPU passes and write one bash script per pass.

Every (layer, group) gets the r values of --r (one shared noise draw across r: --shared-noise); the
--seed-groups get the same r values again with seed 1. Variants are packed in ascending layer order into
passes bounded by --max-streams (memory) and --max-cost stream-layers (wall time: a variant spawned at
layer L costs 40 - L stream-layers, the native stream 40 per pass).

  python3 tools/calib/sens_sweep.py --out-dir .../sens/sweep --r 0.05,0.15,0.35 --extra "--smooth-fp32"
"""

import argparse
import shlex
from pathlib import Path

RECIPE = Path(__file__).resolve().parents[2]


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out-dir", required=True)
    ap.add_argument("--panel", default="/home/sfxnz/projects/data/dsv41-1017/sens/sens_panel.jsonl")
    ap.add_argument("--r", default="0.05,0.15,0.35")
    ap.add_argument("--layers", default="0-39")
    ap.add_argument("--skip-layers", default="", help="layers already covered (e.g. by the gate passes)")
    ap.add_argument("--groups", default="GU,D")
    ap.add_argument("--seed-groups", default="", help="e.g. 2:GU,2:D,14:GU,... (seed 1 repeats)")
    ap.add_argument("--max-streams", type=int, default=14)
    ap.add_argument("--max-cost", type=int, default=480, help="stream-layers per pass incl. native 40")
    ap.add_argument("--extra", default="", help="extra cli.py sens args (e.g. --smooth-fp32)")
    ap.add_argument("--prefix", default="p")
    ap.add_argument("--lock", default="/home/sfxnz/projects/data/dsv41-1017/spark1-gpu.lock")
    ap.add_argument("--mem", default="100g")
    a = ap.parse_args()
    a0, b0 = a.layers.split("-")
    rs = a.r.split(",")
    specs = []  # (layer, spec)
    skip = {int(x) for x in a.skip_layers.split(",") if x}
    for L in range(int(a0), int(b0) + 1):
        if L in skip:
            continue
        for g in a.groups.split(","):
            specs += [(L, f"{L}:{g}:{r}") for r in rs]
    for sg in filter(None, a.seed_groups.split(",")):
        L, g = sg.split(":")
        specs += [(int(L), f"{L}:{g}:{r}:1") for r in rs]
    specs.sort(key=lambda t: t[0])
    passes, cur, cost = [], [], 40
    for L, sp in specs:
        c = 40 - L
        if cur and (len(cur) + 1 > a.max_streams or cost + c > a.max_cost):
            passes.append(cur)
            cur, cost = [], 40
        cur.append(sp)
        cost += c
    if cur:
        passes.append(cur)
    out = Path(a.out_dir)
    out.mkdir(parents=True, exist_ok=True)
    lines = ["#!/bin/bash", "# generated by tools/calib/sens_sweep.py " + " ".join(shlex.quote(x) for x in __import__("sys").argv[1:]),
             "set -u", f"cd {RECIPE}", f"export CALIB_LOCK={a.lock} CALIB_MEM={a.mem}", f"D={out}"]
    for i, ps in enumerate(passes):
        name = f"{a.prefix}{i:02d}"
        vs = " ".join(f"--variant {s}" for s in ps)
        c = 40 + sum(40 - int(s.split(":")[0]) for s in ps)
        lines.append(f"# {name}: {len(ps)} variants, cost {c} stream-layers")
        lines.append(f'if [ ! -s $D/{name}.json ]; then echo "=== {name} start $(date -Is)"; '
                     f"tools/calib/run_gpu.sh sens-{name} python3 tools/calib/cli.py sens --smooth --shared-noise --score-all "
                     f"--panel {a.panel} {a.extra} {vs} --out $D/{name}.json > $D/{name}.log 2>&1; "
                     f'echo "=== {name} rc=$? $(date -Is)"; fi')
    (out / "sweep.sh").write_text("\n".join(lines) + "\n")
    (out / "sweep.sh").chmod(0o755)
    tot = sum(40 + sum(40 - int(s.split(':')[0]) for s in ps) for ps in passes)
    print(f"{len(specs)} variants in {len(passes)} passes, {tot} stream-layers total -> {out / 'sweep.sh'}")


if __name__ == "__main__":
    main()
